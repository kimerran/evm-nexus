// Extracts { abi, bytecode } from the forge `out/` build into the committed
// `artifacts/` directory so the app can import them without compiling Solidity
// at request time (AGENT.md §7). Run via `pnpm --filter @nexus/contracts export`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = ["NexusERC20", "NexusERC721", "NexusERC1155"];
const outDir = join(root, "artifacts");
// Typed, viem-friendly (`as const`) mirrors live in @nexus/types so the app can
// import ABIs + bytecode with full literal typing and no Solidity build step.
const typesDir = join(root, "..", "types", "src", "contracts");
mkdirSync(outDir, { recursive: true });
mkdirSync(typesDir, { recursive: true });

const banner = "// AUTO-GENERATED by packages/contracts/script/export-artifacts.mjs — do not edit.\n";

for (const name of contracts) {
  const forgeArtifact = JSON.parse(
    readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"),
  );
  const abi = forgeArtifact.abi;
  const bytecode = forgeArtifact.bytecode.object;
  const deployedBytecode = forgeArtifact.deployedBytecode.object;

  const artifact = { contractName: name, abi, bytecode, deployedBytecode };
  writeFileSync(join(outDir, `${name}.json`), `${JSON.stringify(artifact, null, 2)}\n`);

  const ts =
    `${banner}\n` +
    `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const ${name}Bytecode = "${bytecode}" as const;\n\n` +
    `export const ${name}DeployedBytecode = "${deployedBytecode}" as const;\n`;
  writeFileSync(join(typesDir, `${name}.ts`), ts);

  console.log(`wrote artifacts/${name}.json + types/src/contracts/${name}.ts (abi: ${abi.length} entries)`);
}

// Barrel that re-exports every generated artifact plus a name→artifact registry.
const barrel =
  `${banner}\n` +
  contracts.map((n) => `export * from "./${n}.js";`).join("\n") +
  "\n\n" +
  contracts.map((n) => `import { ${n}Abi, ${n}Bytecode } from "./${n}.js";`).join("\n") +
  "\n\n" +
  "export const contractArtifacts = {\n" +
  contracts.map((n) => `  ${n}: { abi: ${n}Abi, bytecode: ${n}Bytecode },`).join("\n") +
  "\n} as const;\n\n" +
  "export type ContractName = keyof typeof contractArtifacts;\n";
writeFileSync(join(typesDir, "index.ts"), barrel);
console.log("wrote types/src/contracts/index.ts (barrel + registry)");
